"""
jwt_handler.py - JSON Web Token (JWT) creation and verification
================================================================
This file handles everything related to JWT tokens:
  - Creating access tokens (used for login sessions)
  - Creating refresh tokens (used to get new access tokens)
  - Verifying tokens (checking if a token is valid)
  - Revoking tokens (used for logout)

HOW JWT WORKS (simplified):
  1. User logs in with username + password
  2. Server creates a JWT token containing {username, user_id, role}
  3. Token is signed with our PRIVATE key (RSA256 algorithm)
  4. Frontend stores this token in localStorage
  5. Frontend sends token with every request in the "Authorization" header
  6. Server verifies the token using the PUBLIC key
  7. If valid, the server knows who the user is and what role they have

We use RS256 (RSA + SHA256) instead of HS256 because:
  - Private key signs tokens (kept secret on the server)
  - Public key verifies tokens (can be shared safely)
"""

import os
import secrets
from datetime import timedelta, datetime
from pathlib import Path

from dotenv import load_dotenv
from fastapi import Depends, HTTPException
from fastapi.security import OAuth2PasswordBearer
from jose import jwt, JWTError
from starlette import status

# Load environment variables from .env file
load_dotenv()

# ── OAuth2 Setup ──
# This tells FastAPI where the login endpoint is.
# When a request comes in with "Authorization: Bearer <token>",
# FastAPI automatically extracts the token and passes it to our functions.
oauth2_bearer = OAuth2PasswordBearer(tokenUrl="/login")

# ── JWT Configuration (from .env file) ──
SECRET_KEY = os.getenv("SECRET_KEY", secrets.token_hex(32))
ALGORITHM = os.getenv("ALGORITHM", "RS256")                     # RSA + SHA256
ACCESS_TOKEN_EXPIRE_MINUTES = int(os.getenv("ACCESS_TOKEN_EXPIRE_MINUTES", 15))
REFRESH_TOKEN_EXPIRE_DAYS = int(os.getenv("REFRESH_TOKEN_EXPIRE_DAYS", 7))

# ── RSA Key Paths ──
# These .pem files are generated by generate_keys.py
# Private key: used to SIGN tokens (never share this!)
# Public key: used to VERIFY tokens (safe to share)
PRIVATE_KEY_PATH = Path(os.getenv("PRIVATE_KEY", "keys/private.pem"))
PUBLIC_KEY_PATH = Path(os.getenv("PUBLIC_KEY", "keys/public.pem"))

# Check that the keys exist at startup
if not PRIVATE_KEY_PATH.exists() or not PUBLIC_KEY_PATH.exists():
    raise ValueError(
        "RSA private/public keys not found! "
        "Run 'python generate_keys.py' to create them, "
        "or check your .env PRIVATE_KEY and PUBLIC_KEY paths."
    )

# ── Token Blacklist ──
# When a user logs out, we add their token here so it can't be reused.
# NOTE: This is stored in memory, so it resets when the server restarts.
# For production, you'd want to use Redis or a database table instead.
TOKEN_BLACKLIST = set()


def create_access_token(username: str, user_id: int, expires_delta: timedelta, role: str) -> str:
    """
    Creates a JWT access token for a logged-in user.

    The token contains:
      - sub (subject): the username
      - id: the user's database ID
      - role: the user's role (admin, customer, etc.)
      - exp: when the token expires

    This token is sent back to the frontend after login.
    """
    # Build the payload (the data inside the token)
    payload = {
        "sub": username,
        "id": user_id,
        "role": role
    }
    # Set the expiration time
    expires = datetime.utcnow() + expires_delta
    payload.update({"exp": expires})

    # Read the private key and sign the token
    with open(PRIVATE_KEY_PATH, "r") as key_file:
        private_key = key_file.read()
    return jwt.encode(payload, private_key, algorithm=ALGORITHM)


def create_refresh_token(username: str, user_id: int, expires_delta: timedelta, role: str) -> str:
    """
    Creates a refresh token with a longer expiration time.
    Refresh tokens are used to get a new access token without re-logging in.
    Same structure as access token but lasts longer (days instead of minutes).
    """
    payload = {
        "sub": username,
        "id": user_id,
        "role": role
    }
    expires = datetime.utcnow() + expires_delta
    payload.update({"exp": expires})

    with open(PRIVATE_KEY_PATH, "r") as key_file:
        private_key = key_file.read()
    return jwt.encode(payload, private_key, algorithm=ALGORITHM)


def verify_token(token: str = Depends(oauth2_bearer)) -> dict:
    """
    Verifies a JWT token from an incoming request.

    This is used as a FastAPI "dependency" — you add it to any endpoint
    that requires authentication:

        @app.get("/protected")
        def protected_route(payload: dict = Depends(verify_token)):
            # payload contains {sub, id, role}

    Steps:
      1. Read the public key
      2. Decode the token (checks signature + expiration)
      3. Check if the token has been revoked (logout)
      4. Return the payload if everything is valid
    """
    # Prepare the error response for invalid tokens
    credentials_exception = HTTPException(
        status_code=status.HTTP_401_UNAUTHORIZED,
        detail="Could not validate credentials",
        headers={"WWW-Authenticate": "Bearer"},
    )

    try:
        # Read the public key to verify the token's signature
        with open(PUBLIC_KEY_PATH, "r") as key_file:
            public_key = key_file.read()

        # Decode and verify the token
        payload = jwt.decode(token, public_key, algorithms=[ALGORITHM])

        # Make sure the token has the required fields
        if "sub" not in payload or "role" not in payload:
            raise credentials_exception

        # Check if this token was revoked (user logged out)
        if token in TOKEN_BLACKLIST:
            raise HTTPException(status_code=401, detail="Token has been revoked")

        return payload

    except jwt.ExpiredSignatureError:
        raise HTTPException(status_code=401, detail="Token has expired")
    except JWTError:
        raise credentials_exception


def revoke_token(token: str):
    """
    Adds a token to the blacklist (used during logout).
    After this, the token will be rejected even if it hasn't expired.
    """
    TOKEN_BLACKLIST.add(token)
